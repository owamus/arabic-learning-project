// Builds neon_seed.sql: schema + all sentences, words and glosses as plain SQL,
// for pasting into the Neon SQL Editor when a direct connection from your computer is blocked.
// Usage (from backend/csv):  node make-neon-seed.mjs
import fs from "fs";
import { parse } from "csv-parse/sync";

const read = (f) => parse(fs.readFileSync(f, "utf8"), { columns: true, skip_empty_lines: true, bom: true });
const sentences = read("arabic_sentences.csv");
const glosses = read("word_glosses.csv");

const q = (v) => (v === null || v === undefined || v === "" ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);
// same word splitting as load.js
const tokenize = (plain) => plain.split(/\s+/).map((t) => t.replace(/[^\p{L}\p{N}]/gu, "")).filter(Boolean);

// per-sentence extras come from the gloss file (same on every row of a sentence)
const extras = new Map();
for (const g of glosses) if (!extras.has(g.arabic_plain)) extras.set(g.arabic_plain, g);

const out = [];
out.push("-- Generated by make-neon-seed.mjs. Paste into the Neon SQL Editor and click Run.");
out.push("BEGIN;");
out.push(fs.readFileSync("schema.sql", "utf8"));

out.push("\n-- sentences");
for (const s of sentences) {
  const e = extras.get(s.arabic_plain) || {};
  const tokens = tokenize(s.arabic_plain);
  out.push(
    `INSERT INTO sentences (arabic, arabic_plain, english, level, topic, word_count, source, sentence_type, gif_keyword) VALUES (${[
      q(s.arabic), q(s.arabic_plain), q(s.english), q(s.level), q(s.topic), tokens.length, q(s.source || "ai_generated"),
      q(e.sentence_type), q(e.gif_keyword),
    ].join(", ")}) ON CONFLICT (arabic_plain) DO NOTHING;`,
  );
}

const words = [...new Set(sentences.flatMap((s) => tokenize(s.arabic_plain)))];
out.push("\n-- words");
out.push(`INSERT INTO words (word) VALUES ${words.map((w) => `(${q(w)})`).join(", ")} ON CONFLICT (word) DO NOTHING;`);

out.push("\n-- word-by-word links, glosses and grammar roles");
const rows = [];
for (const g of glosses) {
  const tok = tokenize(g.arabic_plain)[Number(g.position) - 1];
  rows.push(`(${[q(g.arabic_plain), Number(g.position), q(tok), q(g.arabic_word), q(g.english), q(g.role)].join(", ")})`);
}
out.push(`INSERT INTO sentence_words (sentence_id, word_id, position, arabic_form, english, role)
SELECT s.id, w.id, v.pos, v.af, v.en, v.role
FROM (VALUES ${rows.join(",\n")}) AS v(plain, pos, tok, af, en, role)
JOIN sentences s ON s.arabic_plain = v.plain
JOIN words w ON w.word = v.tok
ON CONFLICT (sentence_id, position) DO NOTHING;`);

out.push("\nCOMMIT;");
out.push("SELECT (SELECT count(*) FROM sentences) AS sentences, (SELECT count(*) FROM words) AS words, (SELECT count(*) FROM sentence_words) AS word_links;");
fs.writeFileSync("neon_seed.sql", out.join("\n") + "\n");
console.log(`wrote neon_seed.sql: ${sentences.length} sentences, ${words.length} words, ${rows.length} word links`);
